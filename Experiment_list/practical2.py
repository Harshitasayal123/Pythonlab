# Iteration over a list
numbers = [ 20, 40, 60,80,100]

print("Elements of the list:")
for number in numbers:
    print(number)

# Iteration over a dictionary
student = {
    "name": "Harshita",
    "age": 20,
    "course": "CSE"
}

print("\nDictionary elements:")
for key, value in student.items():
    print(key, ":", value)